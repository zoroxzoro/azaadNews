// Helper methods to query news with publication status enforcement
export const getActiveArticles = () => {
  try {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('azaad_newsroom_articles_v1') : null;
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed.filter((item) => (item.status || 'published') === 'published');
      }
    }
  } catch {
    // Fallback to static mock data
  }
  return mockNews.filter((item) => (item.status || 'published') === 'published');
};

export const getArticleBySlug = (slug) => {
  const matchSlugOrId = (item) =>
    item.slug === slug ||
    String(item.id) === String(slug) ||
    (item.legacyWordPressId && String(item.legacyWordPressId) === String(slug));

  try {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('azaad_newsroom_articles_v1') : null;
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) {
        return parsed.find(matchSlugOrId);
      }
    }
  } catch {
    // Fallback
  }
  return mockNews.find(matchSlugOrId);
};

export const getArticleById = (id) => {
  try {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('azaad_newsroom_articles_v1') : null;
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) {
        return parsed.find((item) => String(item.id) === String(id));
      }
    }
  } catch {
    // Fallback
  }
  return mockNews.find((item) => String(item.id) === String(id));
};

export const getArticlesByCategory = (categorySlug) => {
  return getActiveArticles().filter((item) => item.category === categorySlug);
};

export const getNewsByCategory = (categorySlug, limit) => {
  const filtered = getActiveArticles().filter((item) => item.category === categorySlug);
  return typeof limit === 'number' ? filtered.slice(0, limit) : filtered;
};

export const getBreakingNews = () => {
  return getActiveArticles().filter((item) => item.isBreaking);
};

export const getFeaturedNews = () => {
  return getActiveArticles().filter((item) => item.isFeatured);
};

export const getTrendingNews = (limit = 5) => {
  return getActiveArticles().filter((item) => item.isTrending).slice(0, limit);
};

export const getLatestNews = (limit = 8) => {
  return [...getActiveArticles()]
    .sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt))
    .slice(0, limit);
};

export const getVideoNews = (limit = 4) => {
  return getActiveArticles()
    .filter((item) => !!item.youtubeUrl)
    .sort((a, b) => (b.views || 0) - (a.views || 0))
    .slice(0, limit);
};

export const getMostReadNews = (limit = 5) => {
  return [...getActiveArticles()]
    .sort((a, b) => (b.views || 0) - (a.views || 0))
    .slice(0, limit);
};

export const getUPNewsByCity = (cityKey) => {
  if (!cityKey || cityKey === 'all') {
    return getActiveArticles().filter((item) => item.category === 'uttar-pradesh');
  }
  return getActiveArticles().filter(
    (item) => item.category === 'uttar-pradesh' && item.city === cityKey
  );
};

