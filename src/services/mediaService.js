/**
 * BACKEND-READY SERVICE INTERFACES
 *
 * NOTE: In this frontend prototype, media operations update the shared
 * MediaContext, localStorage, and IndexedDB. When the production backend DAM service
 * is deployed, these async stubs can be mapped directly to REST / S3 / Cloud endpoints:
 *
 * - GET /api/admin/media
 * - POST /api/admin/media
 * - PATCH /api/admin/media/:id
 * - DELETE /api/admin/media/:id
 * - POST /api/admin/media/upload
 */
export const backendMediaService = {
  async fetchMediaAssets() {
    console.info('[Backend DAM Service Ready] GET /api/admin/media');
    return INITIAL_MEDIA_ASSETS;
  },

  async fetchMediaAssetById(id) {
    console.info(`[Backend DAM Service Ready] GET /api/admin/media/${id}`);
    return INITIAL_MEDIA_ASSETS.find((a) => a.id === id) || null;
  },

  async createMediaAsset(assetPayload) {
    console.info('[Backend DAM Service Ready] POST /api/admin/media', assetPayload);
    return { success: true, asset: { ...assetPayload, id: `ASSET-${Date.now()}` } };
  },

  async updateMediaAsset(id, updates) {
    console.info(`[Backend DAM Service Ready] PATCH /api/admin/media/${id}`, updates);
    return { success: true, id, updates };
  },

  async deleteMediaAsset(id) {
    console.info(`[Backend DAM Service Ready] DELETE /api/admin/media/${id}`);
    return { success: true, id };
  },

  async uploadMediaFile(file, metadata = {}) {
    console.info('[Backend DAM Service Ready] POST /api/admin/media/upload', {
      filename: file.name,
      size: file.size,
      mimeType: file.type,
      ...metadata,
    });
    // In production, server uploads to cloud storage (S3/GCS) and returns CDN URL
    return {
      success: true,
      url: URL.createObjectURL(file),
      filename: file.name,
    };
  },
};
